function getDict(lang) {
  return STRINGS[lang] || STRINGS.vi;
}

function tr(lang, key, vars) {
  const dict = getDict(lang);
  let val = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : STRINGS.en[key];
  if (typeof val !== 'string') return val;
  if (!vars) return val;
  return val.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { STRINGS, getDict, tr };
} else if (typeof window !== 'undefined') {
  window.GomTinI18n = { STRINGS, getDict, tr };
}
